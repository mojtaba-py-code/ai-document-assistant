@dataclass(frozen=True, slots=True)
class ZipLimits:
    max_entries: int
    max_uncompressed_bytes: int
    max_ratio: int


@dataclass(frozen=True, slots=True)
class ZipInspection:
    entry_count: int
    total_uncompressed: int
    total_compressed: int
    package_type: str
    main_content_type: str


RATIO_FLOOR_BYTES: Final = 1024 * 1024
"""Compression ratios are only enforced for entries (and archives) at least this large:
tiny XML parts routinely compress by large factors and cannot hurt anyone."""

MAX_CONTENT_TYPES_BYTES: Final = 1024 * 1024
_MAX_ENTRY_NAME = 1024
_EOCD_SIGNATURE = b"PK\x05\x06"
_EOCD64_LOCATOR_SIGNATURE = b"PK\x06\x07"
_EOCD64_SIGNATURE = b"PK\x06\x06"
_EOCD_SIZE = 22
_EOCD64_LOCATOR_SIZE = 20
_EOCD64_MIN_SIZE = 56
_MAX_ZIP_COMMENT = 0xFFFF
_ZIP_ENCRYPTED_FLAGS = 0x0001 | 0x0040  # traditional + strong encryption
_S_IFMT = 0o170000
_S_IFLNK = 0o120000
_DRIVE_PREFIX = re.compile(r"^[A-Za-z]:")
_ENTRY_CONTROL = re.compile("[" + chr(0x00) + "-" + chr(0x1F) + chr(0x7F) + "]")
_NESTED_ARCHIVE_EXTENSIONS: Final = frozenset(
    {
        "zip", "jar", "war", "ear", "apk", "7z", "rar", "gz", "tgz", "bz2", "xz", "zst",
        "tar", "cab", "iso", "lzh", "arj", "msi", "epub",
        "docx", "docm", "dotx", "dotm", "xlsx", "xlsm", "xltx", "xltm", "xlsb", "xlam",
        "pptx", "pptm", "potx", "potm", "ppsx", "ppsm", "odt", "ods", "odp",
    }
)  # fmt: skip

_PACKAGE_MAIN_TYPES: Final[dict[str, str]] = {
    "application/vnd.openxmlformats-officedocument.wordprocessingml.document.main+xml": "docx",
    "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet.main+xml": "xlsx",
    "application/vnd.openxmlformats-officedocument.wordprocessingml.template.main+xml": "dotx",
    "application/vnd.openxmlformats-officedocument.spreadsheetml.template.main+xml": "xltx",
    "application/vnd.openxmlformats-officedocument.presentationml.presentation.main+xml": "pptx",
}
_MACRO_CONTENT_TYPE_MARKERS: Final = ("macroenabled", "vbaproject", "vnd.ms-office.vba")


def _corrupt(detail: str) -> RejectedContent:
    return RejectedContent(
        "The file is not a valid Office document.",
        internal_detail=f"corrupt archive: {detail}",
        extra={"reason": "corrupt_archive"},
    )


def declared_entry_count(handle: BinaryIO) -> int:
    """Entry count from the end-of-central-directory record (ZIP64 aware).

    Read *before* :class:`zipfile.ZipFile` materialises one ``ZipInfo`` per entry, so an
    archive declaring millions of entries is refused without allocating for them.
    """
    handle.seek(0, os.SEEK_END)
    size = handle.tell()
    window = min(size, _EOCD_SIZE + _MAX_ZIP_COMMENT)
    handle.seek(size - window)
    tail = handle.read(window)
    pos = tail.rfind(_EOCD_SIGNATURE)
    if pos < 0 or len(tail) - pos < _EOCD_SIZE:
        raise _corrupt("end of central directory not found")
    fields = struct.unpack("<4s4H2LH", tail[pos : pos + _EOCD_SIZE])
    total_entries: int = fields[4]
    if total_entries != 0xFFFF:
        return total_entries
    eocd_offset = size - window + pos
    if eocd_offset < _EOCD64_LOCATOR_SIZE:
        raise _corrupt("zip64 locator missing")
    handle.seek(eocd_offset - _EOCD64_LOCATOR_SIZE)
    locator = handle.read(_EOCD64_LOCATOR_SIZE)
    signature, _disk, record_offset, _disks = struct.unpack("<4sLQL", locator)
    if signature != _EOCD64_LOCATOR_SIGNATURE or record_offset >= size:
        raise _corrupt("zip64 locator invalid")
    handle.seek(record_offset)
    record = handle.read(_EOCD64_MIN_SIZE)
    if len(record) < _EOCD64_MIN_SIZE or record[:4] != _EOCD64_SIGNATURE:
        raise _corrupt("zip64 end of central directory invalid")
    (total64,) = struct.unpack("<Q", record[32:40])
    return int(total64)


def _check_entry_name(raw_name: str) -> None:
    if not raw_name or len(raw_name) > _MAX_ENTRY_NAME:
        raise _rejected("zip_bad_entry_name", "The archive contains an invalid entry name.")
    if _ENTRY_CONTROL.search(raw_name):
        raise _rejected("zip_bad_entry_name", "The archive contains an invalid entry name.")
    if "\\" in raw_name or raw_name.startswith("/") or _DRIVE_PREFIX.match(raw_name):
        raise _rejected("zip_path_traversal", "The archive contains an unsafe path.")
    if any(part == ".." for part in raw_name.split("/")):
        raise _rejected("zip_path_traversal", "The archive contains an unsafe path.")


def _is_symlink(info: zipfile.ZipInfo) -> bool:
    return (info.external_attr >> 16) & _S_IFMT == _S_IFLNK


def _is_nested_archive(name: str) -> bool:
    return extension_of(name.rsplit("/", 1)[-1]) in _NESTED_ARCHIVE_EXTENSIONS


def classify_content_types(xml: bytes) -> tuple[str, str]:
    """Return ``(package_type, main_content_type)`` from ``[Content_Types].xml``.

    Parsed with ``defusedxml`` (DTDs, entity expansion and external references forbidden).
    Any macro-enabled or VBA content type rejects the package outright, whatever its
    file extension claims.
    """
    try:
        root = SafeElementTree.fromstring(xml, forbid_dtd=True)
    except (SafeElementTree.ParseError, DefusedXmlException, ValueError) as exc:
        raise _corrupt(f"content types unreadable: {type(exc).__name__}") from exc
    content_types: list[str] = []
    for element in root.iter():
        tag = element.tag if isinstance(element.tag, str) else ""
        if tag.rsplit("}", 1)[-1] in {"Default", "Override"}:
            value = element.get("ContentType")
            if value:
                content_types.append(value.strip().lower())
    if any(m in ct for ct in content_types for m in _MACRO_CONTENT_TYPE_MARKERS):
        raise _rejected(
            "ooxml_macro_enabled",
            "Macro-enabled Office documents are not accepted.",
        )
    mains = {_PACKAGE_MAIN_TYPES[ct] for ct in content_types if ct in _PACKAGE_MAIN_TYPES}
    if len(mains) != 1:
        raise _unsupported(
            "not_office_document", "The file is not a Word (.docx) or Excel (.xlsx) document."
        )
    package_type = mains.pop()
    main = next(ct for ct in content_types if _PACKAGE_MAIN_TYPES.get(ct) == package_type)
    return package_type, main


def inspect_zip(source: Path | BinaryIO, limits: ZipLimits) -> ZipInspection:
    """Validate an OOXML archive from its metadata; raise on anything unsafe.

    Enforced: declared entry count (checked from the raw EOCD record first), per-entry and
    whole-archive compression ratio (for sizes >= :data:`RATIO_FLOOR_BYTES`), total declared
    uncompressed size, entry names (no absolute, drive-qualified, backslash, ``..`` or
    control-character names; no case-insensitive duplicates, which OPC treats as the same
    part), no encrypted, symlink or nested-archive entries, only stored/deflated entries, and
    a well-formed ``[Content_Types].xml`` naming exactly one Word or Excel main part.
    """
    if isinstance(source, Path):
        with source.open("rb") as handle:
            return _inspect_zip_handle(handle, limits)
    return _inspect_zip_handle(source, limits)


def _inspect_zip_handle(handle: BinaryIO, limits: ZipLimits) -> ZipInspection:
    count = declared_entry_count(handle)
    if count > limits.max_entries:
        raise _rejected("zip_too_many_entries", "The archive contains too many entries.")
    handle.seek(0)
    try:
        archive = zipfile.ZipFile(handle)
    except (zipfile.BadZipFile, zipfile.LargeZipFile, OSError, EOFError, ValueError) as exc:
        raise _corrupt(type(exc).__name__) from exc
    with archive:
        infos = archive.infolist()
        if len(infos) > limits.max_entries:
            raise _rejected("zip_too_many_entries", "The archive contains too many entries.")
        seen: set[str] = set()
        total_uncompressed = 0
        total_compressed = 0
        content_types: zipfile.ZipInfo | None = None
        for info in infos:
            # orig_filename is the name exactly as stored; ZipInfo.filename is truncated at
            # NUL and has backslashes rewritten on Windows, which would hide both tricks.
            _check_entry_name(info.orig_filename)
            key = info.filename.casefold()
            if key in seen:
                raise _rejected("zip_duplicate_entry", "The archive contains duplicate entries.")
            seen.add(key)
            if info.flag_bits & _ZIP_ENCRYPTED_FLAGS:
                raise _rejected("zip_encrypted_entry", "Encrypted archive entries are not allowed.")
            if _is_symlink(info):
                raise _rejected("zip_symlink_entry", "Symbolic links in archives are not allowed.")
            if info.compress_type not in (zipfile.ZIP_STORED, zipfile.ZIP_DEFLATED):
                raise _rejected(
                    "zip_unsupported_compression", "The archive uses an unsupported compression."
                )
            if not info.is_dir() and _is_nested_archive(info.filename):
                raise _rejected("zip_nested_archive", "Nested archives are not allowed.")
            total_uncompressed += info.file_size
            total_compressed += info.compress_size
            if info.file_size >= RATIO_FLOOR_BYTES and info.file_size > limits.max_ratio * max(
                info.compress_size, 1
            ):
                raise _rejected("zip_ratio_exceeded", "The archive is suspiciously compressed.")
            if total_uncompressed > limits.max_uncompressed_bytes:
                raise _rejected(
                    "zip_too_large_uncompressed", "The archive expands to too much data."
                )
            if key == "[content_types].xml":
                content_types = info
        if total_uncompressed >= RATIO_FLOOR_BYTES and total_uncompressed > limits.max_ratio * max(
            total_compressed, 1
        ):
            raise _rejected("zip_ratio_exceeded", "The archive is suspiciously compressed.")
        if content_types is None:
            raise _unsupported(
                "not_office_document",
                "The file is not a Word (.docx) or Excel (.xlsx) document.",
            )
        if content_types.file_size > MAX_CONTENT_TYPES_BYTES:
            raise _corrupt("content types part too large")
        try:
            with archive.open(content_types) as part:
                xml = part.read(MAX_CONTENT_TYPES_BYTES + 1)
        except (zipfile.BadZipFile, OSError, EOFError, RuntimeError, NotImplementedError) as exc:
            raise _corrupt(f"content types unreadable: {type(exc).__name__}") from exc
        package_type, main = classify_content_types(xml)
    return ZipInspection(
        entry_count=len(infos),
        total_uncompressed=total_uncompressed,
        total_compressed=total_compressed,
        package_type=package_type,
        main_content_type=main,
    )


