# Orchestration
# --------------------------------------------------------------------------- #
@dataclass(frozen=True, slots=True)
class ValidatedContent:
    detected: DetectedType
    archive: ZipInspection | None = None
    text: TextStats | None = None


def validate_content(upload: SpooledUpload, extension: str, limits: ZipLimits) -> ValidatedContent:
    """Run every structural check for ``extension`` over a sealed upload (blocking I/O)."""
    detected = sniff(upload.head, extension)
    if detected.family == "ooxml":
        with upload.open() as handle:
            archive = inspect_zip(handle, limits)
        if archive.package_type != detected.extension:
            raise UnsupportedMediaType(
                f"The file content does not match its .{detected.extension} extension.",
                internal_detail=f"package type {archive.package_type}",
                extra={"reason": "type_mismatch"},
            )
        return ValidatedContent(detected, archive=archive)
    if detected.family == "text":
        stats = validate_text(upload.iter_chunks(), detected.text_encoding or "utf-8")
        return ValidatedContent(detected, text=stats)
    return ValidatedContent(detected)
