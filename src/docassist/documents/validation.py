@dataclass(frozen=True, slots=True)
class DetectedType:
    """What the content really is (decided by magic bytes, never by the client)."""

    extension: str
    mime: str
    family: Family
    text_encoding: str | None = None


_MAGIC: Final[tuple[tuple[bytes, str], ...]] = (
    (b"%PDF-", "pdf"),
    (b"PK\x03\x04", "zip"),
    (b"PK\x05\x06", "zip"),
    (b"PK\x07\x08", "zip"),
    (b"\xd0\xcf\x11\xe0\xa1\xb1\x1a\xe1", "ole2"),
    (b"{\\rtf", "rtf"),
    (b"\x7fELF", "executable"),
    (b"\x1f\x8b", "gzip"),
    (b"7z\xbc\xaf\x27\x1c", "7z"),
    (b"Rar!\x1a\x07", "rar"),
    (codecs.BOM_UTF32_LE, "utf32"),
    (codecs.BOM_UTF32_BE, "utf32"),
)


def magic_kind(head: bytes) -> str | None:
    """Name of the binary format ``head`` starts with, or ``None`` if unrecognised."""
    for magic, kind in _MAGIC:
        if head.startswith(magic):
            return kind
    return None


def _mismatch(extension: str, kind: str | None) -> UnsupportedMediaType:
    return UnsupportedMediaType(
        f"The file content does not match its .{extension} extension.",
        internal_detail=f"extension {extension} but content sniffed as {kind or 'unknown'}",
        extra={"reason": "type_mismatch"},
    )


def sniff(head: bytes, extension: str) -> DetectedType:
    """Decide the real type from the leading bytes and check it matches ``extension``.

    PDF must start with ``%PDF-`` at offset 0 (no leading junk: that is how polyglot files
    are built); DOCX/XLSX must be ZIP archives (OLE2 - legacy or password-protected Office
    files - is refused with a specific message); text formats must not start with any known
    binary signature and their first bytes must pass the text checks of
    :func:`validate_text` (the whole file is checked later).
    """
    ext = extension.lower().lstrip(".")
    mime = MIME_TYPES.get(ext)
    if mime is None:
        raise _unsupported("extension_not_supported", "This file type is not supported.")
    kind = magic_kind(head)
    if ext == "pdf":
        if kind != "pdf":
            raise _mismatch(ext, kind)
        return DetectedType(ext, mime, "pdf")
    if ext in OOXML_EXTENSIONS:
        if kind == "ole2":
            raise _unsupported(
                "legacy_or_encrypted_office",
                "Legacy (97-2003) and password-protected Office files are not supported. "
                "Save the file as an unprotected .docx or .xlsx and upload it again.",
            )
        if kind != "zip":
            raise _mismatch(ext, kind)
        return DetectedType(ext, mime, "ooxml")
    if kind == "utf32":
        raise _unsupported("unsupported_text_encoding", "Text files must be UTF-8 or UTF-16.")
    if kind is not None:
        raise _mismatch(ext, kind)
    encoding = text_encoding(head)
    checker = _TextChecker(encoding)
    checker.feed(head, final=False)
    checker.verify()
    return DetectedType(ext, mime, "text", encoding)


def text_encoding(head: bytes) -> str:
    """Codec for a text upload: BOM-marked UTF-8/UTF-16, otherwise UTF-8."""
    if head.startswith(codecs.BOM_UTF8):
        return "utf-8-sig"
    if head.startswith((codecs.BOM_UTF16_LE, codecs.BOM_UTF16_BE)):
        return "utf-16"
    return "utf-8"


# --------------------------------------------------------------------------- #
# Text validation
# --------------------------------------------------------------------------- #
MAX_CONTROL_RATIO: Final = 0.01
CONTROL_SLACK: Final = 8
# C0 controls except TAB, LF, FF and CR; DEL; C1 controls. Built with chr() on purpose.
_CONTROL_CHARS = re.compile(
    "["
    + chr(0x00)
    + "-"
    + chr(0x08)
    + chr(0x0B)
    + chr(0x0E)
    + "-"
    + chr(0x1F)
    + chr(0x7F)
    + "-"
    + chr(0x9F)
    + "]"
)
_NUL = chr(0)


@dataclass(frozen=True, slots=True)
class TextStats:
    characters: int
    control_characters: int


class _TextChecker:
    def __init__(self, encoding: str) -> None:
        self._decoder = codecs.getincrementaldecoder(encoding)(errors="strict")
        self.characters = 0
        self.controls = 0

    def feed(self, data: bytes, *, final: bool) -> None:
        try:
            text = self._decoder.decode(data, final)
        except UnicodeDecodeError as exc:
            raise _unsupported(
                "invalid_text_encoding",
                "The file is not valid UTF-8 or UTF-16 text.",
            ) from exc
        if _NUL in text:
            raise _unsupported(
                "binary_content", "The file contains binary data and is not a text file."
            )
        self.characters += len(text)
        self.controls += len(_CONTROL_CHARS.findall(text))

    def verify(self) -> TextStats:
        if self.controls > CONTROL_SLACK and self.controls > self.characters * MAX_CONTROL_RATIO:
            raise _unsupported(
                "control_characters",
                "The file contains too many control characters to be a text file.",
            )
        return TextStats(self.characters, self.controls)


def validate_text(chunks: Iterable[bytes], encoding: str) -> TextStats:
    """Decode the whole file strictly with ``encoding``.

    Rejects undecodable bytes, any NUL character, and more than :data:`CONTROL_SLACK`
    control characters when they also exceed :data:`MAX_CONTROL_RATIO` of all characters
    (TAB, LF, CR and FF are allowed).
    """
    checker = _TextChecker(encoding)
    for chunk in chunks:
        checker.feed(chunk, final=False)
    checker.feed(b"", final=True)
    return checker.verify()


