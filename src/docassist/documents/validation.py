"""Upload validation: filename hygiene, bounded spooling, content sniffing, ZIP inspection.

Every upload is treated as hostile. This module decides whether the bytes are *what they
claim to be*; :mod:`docassist.documents.scanning` then decides whether they are *safe*.

* :func:`sanitize_filename` - the client's filename is display metadata only (storage keys are
  generated by the server), but it still reaches UIs, audit trails and ``Content-Disposition``
  headers, so it is reduced to a clean, bounded basename.
* :func:`spool_upload` - copies the request stream into a :class:`SpooledUpload` while hashing
  it (SHA-256) and enforcing the size limit *as bytes arrive*: the upload is aborted with
  :class:`~docassist.core.errors.PayloadTooLarge` at the first chunk that crosses the limit.
  Small uploads stay in memory (their plaintext never touches the disk unencrypted); larger
  ones roll over to a private :func:`tempfile.mkstemp` file (mode 0600 on POSIX) that
  :meth:`SpooledUpload.close` always deletes.
* :func:`sniff` - magic bytes decide the type and the extension must agree with them; the
  client-declared MIME type is recorded by the caller but never trusted.
* :func:`inspect_zip` - OOXML packages are ZIP archives, so zip bombs, path traversal,
  encrypted/symlink/nested entries and macro-enabled package types are rejected using archive
  *metadata* only (nothing is extracted to disk). CPython's :mod:`zipfile` never returns more
  than an entry's declared size, so the declared sizes checked here also bound what any
  in-process consumer can inflate.
* :func:`validate_text` - text formats must be UTF-8 (BOM optional) or BOM-marked UTF-16,
  without NUL characters and with a low proportion of control characters.
"""

