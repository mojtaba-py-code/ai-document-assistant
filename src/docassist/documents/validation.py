# --------------------------------------------------------------------------- #
# Filenames
# --------------------------------------------------------------------------- #
MAX_FILENAME_CHARS: Final = 150
FALLBACK_FILENAME: Final = "document"
_MAX_RAW_FILENAME_CHARS = 1024
_PATH_SEPARATORS = re.compile(r"[/\\]")
_EXTENSION_RE = re.compile(r"[A-Za-z0-9]{1,10}")
_UNSAFE_FILENAME_CHARS = re.compile(r'[<>:"|?*;]')
_WINDOWS_RESERVED = frozenset(
    {"con", "prn", "aux", "nul"}
    | {f"com{i}" for i in range(1, 10)}
    | {f"lpt{i}" for i in range(1, 10)}
)


def _basename(name: str) -> str:
    return _PATH_SEPARATORS.split(name)[-1]


def sanitize_filename(name: str) -> str:
    """Reduce a client-supplied filename to a safe display name.

    Basename only (both ``/`` and ``\\`` count as separators, before *and* after NFKC
    normalisation, which can turn look-alikes such as a fullwidth solidus into a real one);
    invisible, bidi-override and Unicode-tag characters removed; control characters and
    characters reserved by common filesystems replaced; whitespace collapsed; leading and
    trailing dots/spaces stripped; Windows device names defused; at most
    :data:`MAX_FILENAME_CHARS` characters with the extension kept. Falls back to
    ``"document"`` (plus the extension, if any) when nothing usable remains.
    """
    raw = _basename(name or "")[-_MAX_RAW_FILENAME_CHARS:]
    cleaned, _report = sanitize_text(raw)
    cleaned = _basename(cleaned)
    cleaned = _UNSAFE_FILENAME_CHARS.sub("_", cleaned)
    cleaned = " ".join(cleaned.split())
    stem, dot, ext = cleaned.rpartition(".")
    if not dot or not _EXTENSION_RE.fullmatch(ext):
        stem, ext = cleaned, ""
    stem = stem.strip(" .")
    ext = ext.lower()
    if stem.split(".", 1)[0].strip().lower() in _WINDOWS_RESERVED:
        stem = "_" + stem
    budget = MAX_FILENAME_CHARS - (len(ext) + 1 if ext else 0)
    stem = stem[:budget].rstrip(" .") or FALLBACK_FILENAME
    return f"{stem}.{ext}" if ext else stem


def extension_of(filename: str) -> str:
    """Lower-cased extension of an (already sanitised) filename, or ``""``."""
    _stem, dot, ext = filename.rpartition(".")
    return ext.lower() if dot and _EXTENSION_RE.fullmatch(ext) else ""


# --------------------------------------------------------------------------- #
# Spooling
# --------------------------------------------------------------------------- #
class SpooledUpload:
    """The bytes of one upload: in memory up to a threshold, else in a private temp file.

    Use it as a context manager (or call :meth:`close`) - the temp file, if any, is deleted.
    :meth:`open` returns an *independent* reader each time, so validators and scanners can
    run one after another without sharing a file position.
    """

    def __init__(self, *, memory_limit: int, temp_dir: Path | None) -> None:
        self._memory_limit = memory_limit
        self._temp_dir = temp_dir
        self._buffer: bytearray | None = bytearray()
        self._path: Path | None = None
        self._file: BinaryIO | None = None
        self._hash = hashlib.sha256()
        self._digest: str | None = None
        self._head = bytearray()
        self._size = 0

    # ------------------------------------------------------------------ state
    @property
    def size(self) -> int:
        return self._size

    @property
    def head(self) -> bytes:
        """The first :data:`HEAD_BYTES` bytes (for magic-byte sniffing)."""
        return bytes(self._head)

    @property
    def sha256(self) -> str:
        if self._digest is None:
            raise RuntimeError("upload is not sealed yet")
        return self._digest

    @property
    def path(self) -> Path | None:
        """Temp file path if the upload rolled over to disk, else ``None``."""
        return self._path

    @property
    def in_memory(self) -> bool:
        return self._path is None

    # ---------------------------------------------------------------- writing
    async def write(self, data: bytes) -> None:
        if self._digest is not None:
            raise RuntimeError("upload is sealed")
        self._hash.update(data)
        if len(self._head) < HEAD_BYTES:
            self._head += data[: HEAD_BYTES - len(self._head)]
        self._size += len(data)
        if self._buffer is not None and len(self._buffer) + len(data) <= self._memory_limit:
            self._buffer += data
            return
        handle = self._file
        if handle is None:
            handle = await asyncio.to_thread(self._roll_over)
        await asyncio.to_thread(handle.write, data)

    def _roll_over(self) -> BinaryIO:
        directory: str | None = None
        if self._temp_dir is not None:
            self._temp_dir.mkdir(parents=True, exist_ok=True, mode=0o700)
            directory = str(self._temp_dir)
        # mkstemp creates the file with O_EXCL and mode 0600 (owner-only on POSIX).
        fd, name = tempfile.mkstemp(prefix="docassist-upload-", suffix=".part", dir=directory)
        self._path = Path(name)
        handle = os.fdopen(fd, "w+b")
        self._file = handle
        if self._buffer:
            handle.write(self._buffer)
        self._buffer = None
        return handle

    def seal(self) -> None:
        """Finish writing: flush the temp file and fix the digest."""
        if self._digest is not None:
            return
        if self._file is not None:
            self._file.flush()
        self._digest = self._hash.hexdigest()

    # ---------------------------------------------------------------- reading
    def open(self) -> BinaryIO:
        """A fresh, independent binary reader positioned at the start."""
        if self._path is not None:
            return self._path.open("rb")
        return io.BytesIO(bytes(self._buffer or b""))

    def iter_chunks(self, chunk_size: int = READ_CHUNK_BYTES) -> Iterator[bytes]:
        with self.open() as handle:
            while chunk := handle.read(chunk_size):
                yield chunk

    async def aiter_chunks(self, chunk_size: int = READ_CHUNK_BYTES) -> AsyncIterator[bytes]:
        """Async chunk stream (file reads run in a worker thread)."""
        with self.open() as handle:
            while chunk := await asyncio.to_thread(handle.read, chunk_size):
                yield chunk

    # --------------------------------------------------------------- cleanup
    def close(self) -> None:
        """Release memory and delete the temp file (idempotent)."""
        self._buffer = None
        if self._file is not None:
            try:
                self._file.close()
            except OSError:
                log.warning("upload_spool_close_failed")
            self._file = None
        if self._path is not None:
            try:
                self._path.unlink(missing_ok=True)
            except OSError:
                log.exception("upload_spool_delete_failed")
            self._path = None

    def __enter__(self) -> SpooledUpload:
        return self

    def __exit__(
        self,
        exc_type: type[BaseException] | None,
        exc: BaseException | None,
        tb: TracebackType | None,
    ) -> None:
        self.close()


async def spool_upload(
    stream: AsyncIterator[bytes],
    *,
    max_bytes: int,
    temp_dir: Path | None = None,
    memory_limit: int = DEFAULT_MEMORY_SPOOL_BYTES,
) -> SpooledUpload:
    """Copy ``stream`` into a sealed :class:`SpooledUpload`, enforcing ``max_bytes``.

    Raises :class:`PayloadTooLarge` as soon as a chunk would cross the limit (the rest of the
    stream is never read) and :class:`ValidationFailed` for an empty upload. On any error the
    partial spool is deleted before the exception propagates.
    """
    spool = SpooledUpload(memory_limit=memory_limit, temp_dir=temp_dir)
    try:
        await _fill(spool, stream, max_bytes)
    except BaseException:
        spool.close()
        raise
    return spool


async def _fill(spool: SpooledUpload, stream: AsyncIterator[bytes], max_bytes: int) -> None:
    async for chunk in stream:
        if not chunk:
            continue
        if spool.size + len(chunk) > max_bytes:
            raise PayloadTooLarge(
                f"The file exceeds the maximum upload size of {max_bytes} bytes.",
                internal_detail="upload exceeded max_upload_bytes while streaming",
            )
        await spool.write(chunk)
    spool.seal()
    if spool.size == 0:
        raise ValidationFailed("The uploaded file is empty.")


